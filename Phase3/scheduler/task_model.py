"""Task Model and Lifecycle States for OS Scheduling Simulation.

Defines the simulated CPU process/task structure, its lifecycle states,
and origin metadata representing realistic smart traffic monitoring operations.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional, Dict, Any

class TaskStatus(str, Enum):
    """Documented lifecycle states of a task in the CPU scheduler."""
    CREATED = "CREATED"
    READY = "READY"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"


@dataclass
class Task:
    """Represents an operating system task generated by traffic management operations.
    
    Priority Convention:
        Lower numeric value indicates HIGHER priority.
        Priority 1 = Highest (Emergency signal overrides, critical safety checks)
        Priority 2 = High (Actuating traffic lights, real-time vehicle telemetry)
        Priority 3 = Medium (Queue length calculations, DB snapshot writes)
        Priority 4 = Low (Periodic aggregation, performance metrics logging)
        Priority 5 = Background (Simulation summary generation, archive maintenance)
    """
    task_id: str
    task_name: str
    source_module: str
    triggering_event: str
    arrival_time: int
    burst_time: int
    priority: int = 3
    remaining_time: int = field(init=False)
    status: TaskStatus = TaskStatus.CREATED
    start_time: Optional[int] = None
    completion_time: Optional[int] = None
    waiting_time: int = 0
    turnaround_time: int = 0
    execution_order: int = 0

    def __post_init__(self):
        self.remaining_time = self.burst_time

    def to_dict(self) -> Dict[str, Any]:
        """Convert task object to a structured dictionary for tables and database persistence."""
        return {
            "task_id": self.task_id,
            "task_name": self.task_name,
            "source_module": self.source_module,
            "triggering_event": self.triggering_event,
            "arrival_time": self.arrival_time,
            "burst_time": self.burst_time,
            "priority": self.priority,
            "remaining_time": self.remaining_time,
            "status": self.status.value,
            "start_time": self.start_time if self.start_time is not None else 0,
            "completion_time": self.completion_time if self.completion_time is not None else 0,
            "waiting_time": self.waiting_time,
            "turnaround_time": self.turnaround_time,
            "execution_order": self.execution_order
        }

    def copy(self) -> "Task":
        """Create a fresh copy of the task for reproducible algorithm comparisons."""
        t = Task(
            task_id=self.task_id,
            task_name=self.task_name,
            source_module=self.source_module,
            triggering_event=self.triggering_event,
            arrival_time=self.arrival_time,
            burst_time=self.burst_time,
            priority=self.priority
        )
        return t
